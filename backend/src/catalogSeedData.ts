function makeSvgArtworkUrl(title: string, subtitle: string, accentHex: string, bgHex: string, isBackdrop = false): string {
  const width = isBackdrop ? 1280 : 600;
  const height = isBackdrop ? 720 : 900;
  const safeTitle = title.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const safeSub = subtitle.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
    <defs>
      <linearGradient id="bg" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgHex}" />
        <stop offset="55%" stop-color="#090d16" />
        <stop offset="100%" stop-color="#050507" />
      </linearGradient>
      <radialGradient id="glow" cx="75%" cy="25%" r="60%">
        <stop offset="0%" stop-color="${accentHex}" stop-opacity="0.42" />
        <stop offset="100%" stop-color="${accentHex}" stop-opacity="0" />
      </radialGradient>
    </defs>
    <rect width="100%" height="100%" fill="url(#bg)" />
    <rect width="100%" height="100%" fill="url(#glow)" />
    <circle cx="${width * 0.8}" cy="${height * 0.22}" r="${Math.min(width, height) * 0.28}" fill="none" stroke="${accentHex}" stroke-opacity="0.18" stroke-width="2" />
    <circle cx="${width * 0.8}" cy="${height * 0.22}" r="${Math.min(width, height) * 0.18}" fill="none" stroke="${accentHex}" stroke-opacity="0.28" stroke-width="1.5" />
    <rect x="${isBackdrop ? 80 : 44}" y="${isBackdrop ? height - 240 : height - 290}" width="64" height="5" rx="2.5" fill="${accentHex}" />
    <text x="${isBackdrop ? 80 : 44}" y="${isBackdrop ? height - 195 : height - 240}" fill="#f8fafc" font-family="system-ui, -apple-system, sans-serif" font-size="${isBackdrop ? 52 : 38}" font-weight="800" letter-spacing="-0.5">${safeTitle}</text>
    <text x="${isBackdrop ? 80 : 44}" y="${isBackdrop ? height - 145 : height - 195}" fill="#94a3b8" font-family="system-ui, -apple-system, sans-serif" font-size="${isBackdrop ? 24 : 18}" font-weight="600" letter-spacing="2">${safeSub.toUpperCase()}</text>
    <text x="${isBackdrop ? 80 : 44}" y="${isBackdrop ? 72 : 56}" fill="${accentHex}" font-family="system-ui, -apple-system, sans-serif" font-size="16" font-weight="800" letter-spacing="4">ZIRA CINEMA</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

